type screenLedgerMarket struct {
	screenHistoryFixture
	close time.Time
}

func (m screenLedgerMarket) DayKlines(_ string, _, _ time.Time) (extend.Klines, error) {
	yesterday := m.close.AddDate(0, 0, -1)
	return extend.Klines{{Kline: &protocol.Kline{Time: yesterday, Open: 10, High: 10, Low: 10, Close: 10}}}, nil
}

type screenLedgerFeed struct {
	close time.Time
}

func (f screenLedgerFeed) minutes(_ context.Context, code string, at time.Time) (protocol.Klines, error) {
	if code == "sh600001" {
		return nil, nil
	}
	return protocol.Klines{{Time: f.close, Open: 10, High: 11, Low: 10, Close: 11, Volume: 100}}, nil
}

func (f screenLedgerFeed) quotes(_ context.Context, _ []string, at time.Time) (map[string]*protocol.Kline, error) {
	return map[string]*protocol.Kline{"sh600000": {Time: at, Open: 10, High: 11, Low: 10, Close: 11, Volume: 100}}, nil
}

func TestScreenLedgerCloseBuyAndSellSurviveRestart(t *testing.T) {
	day := time.Date(2026, 11, 12, 15, 0, 0, 0, protocol.Location())
	root := t.TempDir()
	server := newServerWithStores(NewAnalysisStore(root), NewCandidateStore(root))
	service := server.screen
	market := screenLedgerMarket{close: day}
	service.market = market
	db, err := openScreenLedger(service.ledgerPath())
	if err != nil {
		t.Fatal(err)
	}
	defer func() { db.Close() }()
	config, err := service.load()
	if err != nil {
		t.Fatal(err)
	}
	strategy := screenStrategy{ID: "st_20261112T070000000Z_00000001", Name: "收盘策略", Enabled: true,
		Buy:   &builder.BuilderNode{Type: "condition", ComponentID: "buy_all"},
		Risks: []*builder.BuilderNode{{Type: "condition", ComponentID: "risk_fixed_tp", Params: map[string]any{"pct": 5.0}}}}
	config.Strategies = append(config.Strategies, strategy)
	result, complete, err := captureScreenClose(context.Background(), market, screenLedgerFeed{day}, config, day.Add(time.Minute))
	if err != nil || !complete || len(result.Matches) != 1 {
		t.Fatalf("close: %+v, %t, %v", result, complete, err)
	}
	for range 2 {
		if err := persistScreenBuys(db, config, result); err != nil {
			t.Fatal(err)
		}
	}
	// An identical candidate generated by a scan at 14:59 must stay a preview.
	result.Matches[0].Time = day.Add(-time.Minute).Format(time.DateTime)
	if err := persistScreenBuys(db, config, result); err != nil {
		t.Fatal(err)
	}
	rows, err := screenEntries(db, "")
	if err != nil || len(rows) != 1 || rows[0].Signal.BuyTime != day.Format(time.DateTime) || rows[0].Signal.SellTime != "" {
		t.Fatalf("entries = %+v, %v", rows, err)
	}
	readCount := 0
	next := day.AddDate(0, 0, 1).Add(-5 * time.Hour)
	market.close = day.AddDate(0, 0, 1)
	read := func(_ context.Context, _ string, at time.Time) (protocol.Klines, error) {
		readCount++
		return protocol.Klines{{Time: at, Open: 11, High: 12, Low: 11, Close: 12}}, nil
	}
	if err := scanScreenExits(context.Background(), db, market, read, day.Add(time.Minute)); err != nil || readCount != 0 {
		t.Fatalf("T+1 failed: %v, reads %d", err, readCount)
	}
	failRead := func(context.Context, string, time.Time) (protocol.Klines, error) {
		return nil, errors.New("行情断线")
	}
	if err := scanScreenExits(context.Background(), db, market, failRead, next); err == nil {
		t.Fatal("feed failure was ignored")
	}
	rows, err = screenEntries(db, next.Format(time.DateOnly))
	if err != nil || len(rows) != 1 {
		t.Fatalf("failed pass closed a trade: %+v %v", rows, err)
	}
	quiet := func(_ context.Context, _ string, at time.Time) (protocol.Klines, error) {
		return protocol.Klines{{Time: at, Open: 11, High: 11, Low: 11, Close: 11}}, nil
	}
	if err := scanScreenExits(context.Background(), db, market, quiet, next.Add(-time.Minute)); err != nil {
		t.Fatal(err)
	}
	rows, err = screenEntries(db, next.Format(time.DateOnly))
	if err != nil || len(rows) != 1 {
		t.Fatalf("non-matching price closed a trade: %+v %v", rows, err)
	}
	if err := scanScreenExits(context.Background(), db, market, read, next); err != nil {
		t.Fatal(err)
	}
	if err := db.Close(); err != nil {
		t.Fatal(err)
	}
	db, err = openScreenLedger(service.ledgerPath())
	if err != nil {
		t.Fatal(err)
	}
	if err := scanScreenExits(context.Background(), db, market, read, next.Add(time.Minute)); err != nil || readCount != 1 {
		t.Fatalf("closed trade was evaluated again: reads %d, %v", readCount, err)
	}
	rows, err = screenEntries(db, "")
	if err != nil || len(rows) != 1 || rows[0].Signal.SellPrice != 12 || rows[0].Signal.SellTime != next.Format(time.DateTime) {
		t.Fatalf("completed entry = %+v, %v", rows, err)
	}
	// Retrying the same completion cannot publish another event.
	if err := closeScreenEntry(db, rows[0], rows[0].Signal); err != nil {
		t.Fatal(err)
	}
	events, err := screenEvents(db, 0, next.Format(time.DateOnly))
	if err != nil || len(events) != 1 || events[0].Signal.SellPrice != 12 || events[0].Type != "sell" {
		t.Fatalf("events = %+v, %v", events, err)
	}
	service.now = func() time.Time { return next }
	httpServer := httptest.NewServer(server.Handler())
	defer httpServer.Close()
	ws, _, err := websocket.DefaultDialer.Dial("ws"+strings.TrimPrefix(httpServer.URL, "http")+"/api/screen/events?after=0", nil)
	if err != nil {
		t.Fatal(err)
	}
	defer ws.Close()
	ws.SetReadDeadline(time.Now().Add(2 * time.Second))
	var event screenSaleEvent
	if err := ws.ReadJSON(&event); err != nil || event.ID != events[0].ID {
		t.Fatalf("websocket = %+v, %v", event, err)
	}
	// A replay row with different prices must never overwrite the ledger.
	replay := rows[0].Signal
	replay.Tracked, replay.SellPrice = false, 99
	historyRun := screener.History{Rows: []screener.Signal{replay}}
	if err := saveScreenReplay(context.Background(), service.ledgerPath(), config, historyRun, 60, map[screener.SignalKey]screenPosition{replay.Key(): rows[0]}); err != nil {
		t.Fatal(err)
	}
	history, _, _, err := service.historySnapshot(false)
	if err != nil || len(history) != 1 || !history[0].Tracked || history[0].SellPrice != 12 {
		t.Fatalf("history = %+v, %v", history, err)
	}
}

func TestScreenCloseRetryDoesNotDuplicateEntries(t *testing.T) {
	db, err := openScreenLedger(filepath.Join(t.TempDir(), "ledger.db"))
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	config := screenConfig{Strategies: []screenStrategy{{ID: "macd-premium", Name: "MACD精选", Enabled: true}}}
	result := screener.Result{AsOf: "2026-11-12 15:00:00", Matches: []screener.Match{{Code: "sh600000", Time: "2026-11-12 15:00:00", Price: 10, Hits: []screener.Hit{{ID: "macd-premium"}}}}}
	if err := persistScreenBuys(db, config, result); err != nil {
		t.Fatal(err)
	}
	result.Matches[0].Price = 12
	if err := persistScreenBuys(db, config, result); err != nil {
		t.Fatal(err)
	}
	rows, err := screenEntries(db, "")
	if err != nil || len(rows) != 1 || rows[0].Signal.BuyPrice != 10 {
		t.Fatalf("retries overwrote entry: %+v, %v", rows, err)
	}
}
